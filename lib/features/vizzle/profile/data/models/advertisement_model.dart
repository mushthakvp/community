import '../../domain/entities/advertisement_entity.dart';

class AdvertisementModel extends AdvertisementEntity {
  const AdvertisementModel({
    required super.id,
    required super.userId,
    required super.district,
    required super.title,
    required super.description,
    required super.shareLink,
    required super.images,
    required super.category,
    required super.subCategory,
    required super.latitude,
    required super.longitude,
    required super.address,
    super.year,
    required super.age,
    super.kilometers,
    super.price,
    required super.phone,
    required super.fuelType,
    required super.color,
    required super.transmissionType,
    required super.usage,
    required super.condition,
    super.engineCapacity,
    required super.sellerType,
    super.warrenty,
    required super.brand,
    required super.memory,
    required super.processor,
    required super.hardDrive,
    required super.type,
    required super.duration,
    required super.rating,
    required super.model,
    required super.damage,
    required super.damageDetails,
    required super.materials,
    required super.batteryPercentage,
    required super.version,
    required super.accompaniments,
    super.carrierLock,
    required super.imeiNumber,
    super.number,
    required super.storageCapacity,
    required super.memoryRam,
    required super.insights,
    required super.membersSaved,
    required super.membersShared,
    required super.reports,
    required super.isRemoved,
    required super.isDeleted,
    required super.isSold,
    super.renewDate,
    required super.renewed,
    required super.isApproved,
    required super.approvalStatus,
    super.createdAt,
    super.updatedAt,
    super.v,
    super.rejectionReason,
  });

  factory AdvertisementModel.fromJson(Map<String, dynamic> json) {
    return AdvertisementModel(
      id: json['_id'] ?? json['id'] ?? '',
      userId: json['userId'] ?? '',
      district: json['district'] ?? '',
      title: json['title'] ?? '',
      description: json['description'] ?? '',
      shareLink: json['shareLink'] ?? '',
      images: List<String>.from(json['images'] ?? []),
      category: json['category'] ?? '',
      subCategory: json['subCategory'] ?? '',
      latitude: json['latitude'] ?? '',
      longitude: json['longitude'] ?? '',
      address: json['address'] ?? '',
      year: json['year'],
      age: json['age'] ?? '',
      kilometers: json['kilometers'],
      price: json['price']?.toDouble(),
      phone: json['phone'] ?? '',
      fuelType: json['fuelType'] ?? '',
      color: json['color'] ?? '',
      transmissionType: json['transmissionType'] ?? '',
      usage: json['usage'] ?? '',
      condition: json['condition'] ?? '',
      engineCapacity: json['engineCapacity'],
      sellerType: json['sellerType'] ?? '',
      warrenty: json['warrenty'],
      brand: json['brand'] ?? '',
      memory: json['memory'] ?? '',
      processor: json['processor'] ?? '',
      hardDrive: json['hardDrive'] ?? '',
      type: json['type'] ?? '',
      duration: json['duration'] ?? '',
      rating: json['rating'] ?? '',
      model: json['model'] ?? '',
      damage: json['damage'] ?? '',
      damageDetails: List<String>.from(json['damageDetails'] ?? []),
      materials: List<String>.from(json['materials'] ?? []),
      batteryPercentage: json['batteryPercentage'] ?? '',
      version: json['version'] ?? '',
      accompaniments: List<String>.from(json['accompaniments'] ?? []),
      carrierLock: json['carrierLock'],
      imeiNumber: json['imeiNumber'] ?? '',
      number: json['number'],
      storageCapacity: json['storageCapacity'] ?? '',
      memoryRam: json['memoryRam'] ?? '',
      insights: List<String>.from(json['insights'] ?? []),
      membersSaved: List<dynamic>.from(json['membersSaved'] ?? []),
      membersShared: List<String>.from(json['membersShared'] ?? []),
      reports: List<dynamic>.from(json['reports'] ?? []),
      isRemoved: json['isRemoved'] ?? false,
      isDeleted: json['isDeleted'] ?? false,
      isSold: json['isSold'] ?? false,
      renewDate: json['renewDate'] != null
          ? DateTime.parse(json['renewDate'])
          : null,
      renewed: json['renewed'] ?? false,
      isApproved: json['isApproved'] ?? false,
      approvalStatus: json['approvalStatus'] ?? '',
      createdAt: json['createdAt'] != null
          ? DateTime.parse(json['createdAt'])
          : null,
      updatedAt: json['updatedAt'] != null
          ? DateTime.parse(json['updatedAt'])
          : null,
      v: json['__v'],
      rejectionReason: json['rejectionReason'],
    );
  }

  Map<String, dynamic> toJson() {
    return {
      '_id': id,
      'userId': userId,
      'district': district,
      'title': title,
      'description': description,
      'shareLink': shareLink,
      'images': images,
      'category': category,
      'subCategory': subCategory,
      'latitude': latitude,
      'longitude': longitude,
      'address': address,
      'year': year,
      'age': age,
      'kilometers': kilometers,
      'price': price,
      'phone': phone,
      'fuelType': fuelType,
      'color': color,
      'transmissionType': transmissionType,
      'usage': usage,
      'condition': condition,
      'engineCapacity': engineCapacity,
      'sellerType': sellerType,
      'warrenty': warrenty,
      'brand': brand,
      'memory': memory,
      'processor': processor,
      'hardDrive': hardDrive,
      'type': type,
      'duration': duration,
      'rating': rating,
      'model': model,
      'damage': damage,
      'damageDetails': damageDetails,
      'materials': materials,
      'batteryPercentage': batteryPercentage,
      'version': version,
      'accompaniments': accompaniments,
      'carrierLock': carrierLock,
      'imeiNumber': imeiNumber,
      'number': number,
      'storageCapacity': storageCapacity,
      'memoryRam': memoryRam,
      'insights': insights,
      'membersSaved': membersSaved,
      'membersShared': membersShared,
      'reports': reports,
      'isRemoved': isRemoved,
      'isDeleted': isDeleted,
      'isSold': isSold,
      'renewDate': renewDate?.toIso8601String(),
      'renewed': renewed,
      'isApproved': isApproved,
      'approvalStatus': approvalStatus,
      'createdAt': createdAt?.toIso8601String(),
      'updatedAt': updatedAt?.toIso8601String(),
      '__v': v,
      'rejectionReason': rejectionReason,
    };
  }
}
